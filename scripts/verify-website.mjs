/* global console, process */
import { readFile, stat } from 'node:fs/promises'
import path from 'node:path'

const root = path.resolve('site')
const files = [
  'index.html',
  'styles.css',
  'main.js',
  'demo/index.html',
  'favicon.svg',
  'og.svg',
  'llms.txt',
  'fonts/GeistSans.woff2',
  'fonts/GeistMono.woff2',
  'fonts/OFL.txt',
]
const failures = []
for (const relative of files) {
  try {
    const info = await stat(path.join(root, relative))
    if (!info.isFile() || !info.size) failures.push(`${relative} is empty`)
  } catch {
    failures.push(`${relative} is missing`)
  }
}
for (const relative of ['index.html', 'demo/index.html']) {
  const html = await readFile(path.join(root, relative), 'utf8')
  for (const token of ['<!doctype html', '<title', 'name="description"'])
    if (!html.toLowerCase().includes(token.toLowerCase()))
      failures.push(`${relative} lacks ${token}`)
  if (html.includes('�'))
    failures.push(`${relative} contains replacement characters`)
}
const entry = await readFile(path.resolve('index.html'), 'utf8')
if (
  !entry.includes('content="0; url=./site/"') ||
  !entry.includes('href="./site/"')
)
  failures.push(
    'Pages root lacks its script-free landing entry and fallback link',
  )
const home = await readFile(path.join(root, 'index.html'), 'utf8')
for (const phrase of [
  'Typed values are never captured',
  'pixelates before persistence',
  'main app itself must never',
  'single-user and has no authentication system',
  'safe simulation',
])
  if (!home.toLowerCase().includes(phrase.toLowerCase()))
    failures.push(`homepage lacks scope/privacy phrase: ${phrase}`)
if (/(?:href|src)=["']\/(?!\/)/.test(home))
  failures.push(
    'Homepage contains host-root paths that escape the Pages project',
  )
if (home.includes('/blob/master/'))
  failures.push('Homepage renderer link points to the old branch')
const css = await readFile(path.join(root, 'styles.css'), 'utf8')
if (/@import\b/.test(css) || /https?:\/\//.test(css))
  failures.push('Landing stylesheet depends on an external font/style service')
const demo = await readFile(path.join(root, 'demo/index.html'), 'utf8')
for (const phrase of [
  'StepDoc HTML export',
  'This guide was generated by StepDoc.',
  'Share an internal guide without exposing your workspace',
  'data:image/svg+xml;base64',
])
  if (!demo.includes(phrase))
    failures.push(`exported guide lacks generated evidence: ${phrase}`)
if (/<script\b/i.test(demo))
  failures.push('Self-contained guide unexpectedly includes script')
if (failures.length) {
  console.error(failures.map((value) => `- ${value}`).join('\n'))
  process.exit(1)
}
console.log(
  'Website verified: Pages root entry, project-relative links/assets, local licensed fonts, privacy/scope disclosures and production-rendered HTML guide.',
)
