import { describe, expect, it } from 'vitest'
import { renderStandaloneHtml } from './html-export'

describe('standalone HTML export', () => {
  it('escapes guide content, embeds images, and identifies StepDoc as the generator', () => {
    const html = renderStandaloneHtml({ title: 'Safe <guide>', description: 'Do this & that', sourceUrl: 'internal.example', steps: [{ text: 'Click "Save"', imageDataUrl: 'data:image/webp;base64,AA==' }] })
    expect(html).toContain('<meta name="generator" content="StepDoc HTML export">')
    expect(html).toContain('Safe &lt;guide&gt;')
    expect(html).toContain('Do this &amp; that')
    expect(html).toContain('data:image/webp;base64,AA==')
    expect(html).toContain('This guide was generated by StepDoc.')
  })
})
